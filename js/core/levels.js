/**
 * Convierte un nivel de COLORING_PRESETS al formato de opciones de los generadores
 * (strokeWidthMm, minCellAreaMm2, includeFrames, etc.).
 */
export function levelToGeneratorOpts(key) {
  const p = COLORING_PRESETS[key];
  if (!p) return null;
  return {
    complexity: p.complexity,
    densityFactor: p.densityFactor,
    strokeWidthMm: p.strokeWidth,
    spacing: p.spacing,
    minCellAreaMm2: p.minCellArea,
    detailSimplification: p.detailSimplification,
    outlineMode: !!p.outlineMode,
    includeFrames: !!p.frames,
  };
}
